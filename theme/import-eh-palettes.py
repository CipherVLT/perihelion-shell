def f32(x):
    return struct.unpack("f", struct.pack("f", x))[0]


def to_hex(rgb):
    """theme_data.zig rgbToHex, in f32 like Zig: @round(clamp(c) * 255)."""
    out = []
    for c in rgb:
        v = f32(f32(min(1.0, max(0.0, f32(c)))) * f32(255.0))
        out.append(int(v + 0.5))  # @round: half away from zero (v >= 0)
    return "#{:02x}{:02x}{:02x}".format(*out)


def luminance(h):
    def lin(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(h[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def slug(name):
    s = name.lower().replace("é", "e").replace("_", "-")
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s or "palette"


_NUM3 = r"\.\{\s*([-\d.e]+)\s*,\s*([-\d.e]+)\s*,\s*([-\d.e]+)\s*\}"
TRIPLE = re.compile(r"\.(\w+)\s*=\s*" + _NUM3)                  # .primary = .{ r, g, b }
FIELD = re.compile(r"\b(\w+)\s*:\s*\[3\]f32\s*=\s*" + _NUM3)     # primary: [3]f32 = .{ r, g, b }
HEAD = re.compile(r'\.name\s*=\s*"((?:[^"\\]|\\.)*)"\s*,\s*\.source\s*=\s*"([^"]*)"\s*,'
                  r'\s*\.variant\s*=\s*"([^"]*)"')


def parse(text):
    """Palette struct defaults, then each `.{ .name = ... }` entry of presets."""
    m = re.search(r"pub const Palette = struct \{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit(f"import-eh-palettes: no Palette struct in {TABLE}; the format changed")
    defaults = {k: tuple(float(v) for v in vs) for k, *vs in FIELD.findall(m.group(1))}
    missing = {r for r, _ in ROLES} - set(defaults)
    if missing:
        sys.exit(f"import-eh-palettes: Palette struct lacks {sorted(missing)}; the format changed")
    start = text.find("pub const presets")
    if start < 0:
        sys.exit(f"import-eh-palettes: no presets table in {TABLE}")
    body = text[text.index("{", text.index("=", start)) + 1:]
    presets, depth, i, entry_start = [], 0, 0, None
    while i < len(body):  # split the array into its top-level `.{ ... }` entries
        ch = body[i]
        if ch == '"':
            i = body.index('"', i + 1)
            while body[i - 1] == "\\":
                i = body.index('"', i + 1)
        elif ch == "{":
            if depth == 0:
                entry_start = i
            depth += 1
        elif ch == "}":
            if depth == 0:
                break  # end of the array
            depth -= 1
            if depth == 0:
                entry = body[entry_start:i + 1]
                h = HEAD.search(entry)
                if not h:
                    sys.exit("import-eh-palettes: an entry without name/source/variant:\n"
                             + entry[:200])
                pal = dict(defaults)
                for k, *vs in TRIPLE.findall(entry):
                    if k not in pal:
                        sys.exit(f"import-eh-palettes: unknown role .{k} in {h.group(1)!r}")
                    pal[k] = tuple(float(v) for v in vs)
                name = h.group(1).encode().decode("unicode_escape").encode("latin-1").decode()
                presets.append({"name": name, "source": h.group(2), "variant": h.group(3),
                                "palette": pal})
        i += 1
    return presets


def assign_ids(presets):
    """family/variant for the named families; google/<name> for the big
    Google set, with -light on the light one when a name is in both lists."""
    ids, seen = [], {}
    for p in presets:
        p["light"] = p["variant"] in LIGHT_VARIANTS
        if p["source"] == "google":
            base = slug(p["name"])
            twins = [q for q in presets if q["source"] == "google" and slug(q["name"]) == base]
            if len(twins) > 1 and p["light"]:
                base += "-light"  # the dark twin keeps the bare name
        else:
            base = slug(p["variant"])
        pid = f'{slug(p["source"])}/{base}'
        n = seen.get(pid, 0) + 1
        seen[pid] = n
        if n > 1:
            pid += f"-{n}"
        p["id"] = pid
        ids.append(pid)
    return ids


def eh_text(checkout, ref):
    try:
        return subprocess.run(["git", "-C", checkout, "show", f"{ref}:{TABLE}"], check=True,
                              capture_output=True, text=True).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit(f"import-eh-palettes: can't read {TABLE} at {ref} in {checkout}: {e}")


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(prog="import-eh-palettes",
                                 description="Event Horizon's colour themes -> Perihelion palettes")
    ap.add_argument("checkout", nargs="?", default=os.path.expanduser("~/src/Event-Horizon"))
    ap.add_argument("--ref", default="HEAD", help="Event Horizon commit (default: HEAD)")
    ap.add_argument("--out", default=os.path.join(here, "palettes"))
    args = ap.parse_args(argv)

    commit = subprocess.run(["git", "-C", args.checkout, "rev-parse", args.ref],
                            capture_output=True, text=True).stdout.strip()
    if not commit:
        sys.exit(f"import-eh-palettes: {args.ref} isn't a commit in {args.checkout}")
    presets = parse(eh_text(args.checkout, commit))
    assign_ids(presets)
    excluded = sorted(p["id"] for p in presets if EXCLUDE.search(p["id"]))
    presets = [p for p in presets if not EXCLUDE.search(p["id"])]

    # Everything under --out is generated: start clean so a palette Event
    # Horizon dropped doesn't linger.
    if os.path.isdir(args.out):
        shutil.rmtree(args.out)
    low, mismatch, families = [], [], {}
    for p in presets:
        colors = {key: to_hex(p["palette"][role]) for role, key in ROLES}
        ratio = round(contrast(colors["foreground"], colors["background"]), 2)
        doc = {
            "id": p["id"], "name": p["name"],
            "family": slug(p["source"]),
            "family_name": FAMILY_NAMES.get(p["source"], p["source"].replace("-", " ").title()),
            "variant": p["variant"], "light": p["light"],
            "colors": colors,
            "contrast": ratio,
            "origin": f"event-horizon@{commit[:7]}",
        }
        if ratio < MIN_CONTRAST:
            doc["low_contrast"] = True
            low.append((p["id"], ratio))
        # Event Horizon files it under Light/Dark by name; say so when the
        # background disagrees (a "light" palette on a near-black background).
        if (luminance(colors["background"]) > 0.18) != p["light"]:
            doc["light_mismatch"] = True
            mismatch.append(p["id"])
        path = os.path.join(args.out, p["id"] + ".json")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(doc, f, ensure_ascii=False, indent=2)
            f.write("\n")
        fam = families.setdefault(doc["family"], {"dark": 0, "light": 0})
        fam["light" if p["light"] else "dark"] += 1

    source = {
        "event_horizon": "https://github.com/Event-Horizon-desktop-environment/Event-Horizon",
        "commit": commit, "file": TABLE, "license": "GPL-3.0 (Event Horizon)",
        "generated_by": "theme/import-eh-palettes.py",
        "count": len(presets), "families": families,
        "low_contrast": [{"id": i, "contrast": r} for i, r in low],
        "light_mismatch": mismatch,
        "excluded": {"reason": "Monokai publishes no open licence", "ids": excluded},
    }
    with open(os.path.join(args.out, "SOURCE.json"), "w", encoding="utf-8") as f:
        json.dump(source, f, ensure_ascii=False, indent=2)
        f.write("\n")
    with open(os.path.join(args.out, "NOTICE.md"), "w", encoding="utf-8") as f:
        f.write(NOTICE.format(file=TABLE, commit=commit))

    print(f"import-eh-palettes: {len(presets)} palettes from Event Horizon {commit[:7]} -> {args.out}"
          f" ({len(excluded)} Monokai ones left out)")
    for fam, n in families.items():
        print(f"  {fam:12} {n['dark']:3} dark  {n['light']:3} light")
    if low:
        print(f"  {len(low)} below {MIN_CONTRAST}:1 text contrast:")
        for i, r in low:
            print(f"    {i}  {r}:1")
    if mismatch:
        print(f"  {len(mismatch)} filed as light/dark against their background: {', '.join(mismatch)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
